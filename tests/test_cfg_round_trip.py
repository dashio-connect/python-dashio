import unittest

from dashio import Button, Color, ColorPicker, ColorPickerStyle, ControlPosition, Table
from dashio.iotcontrol.control import _get_color


class TestCfgRoundTrip(unittest.TestCase):
    def test_get_color_from_name(self):
        self.assertEqual(_get_color("White Smoke"), Color.WHITE_SMOKE, "Color names exported by the Dash app should decode")

    def test_get_color_from_number(self):
        self.assertEqual(_get_color(str(Color.RED.value)), Color.RED, "Color numbers generated by the library should decode")

    def test_get_color_hex_and_empty(self):
        self.assertEqual(_get_color("#FF0000"), "#FF0000", "Hex colors should be returned unchanged")
        self.assertEqual(_get_color(""), "", "Empty colors should be returned unchanged")

    def test_button_cfg_round_trip(self):
        button = Button(
            "BTTN1",
            "A Button",
            on_color=Color.RED,
            off_color=Color.DARK_GREEN,
            control_position=ControlPosition(0.1, 0.2, 0.3, 0.4)
        )
        cfg = button.get_cfg64(["", "DEVICEID", "DASHID", "1"])[0]
        cfg["parentID"] = "VIEW1"
        new_button = Button.from_cfg_dict(cfg)
        new_cfg = new_button.get_cfg64(["", "DEVICEID", "DASHID", "1"])[0]
        self.assertEqual(new_cfg["onColor"], cfg["onColor"], "onColor should survive a round trip")
        self.assertEqual(new_cfg["offColor"], cfg["offColor"], "offColor should survive a round trip")

    def test_color_picker_cfg_round_trip(self):
        picker = ColorPicker("CLR1", style=ColorPickerStyle.SPECTRUM, control_position=ControlPosition(0.1, 0.2, 0.3, 0.4))
        cfg = picker.get_cfg64(["", "DEVICEID", "DASHID", "1"])[0]
        self.assertEqual(cfg["pickerStyle"], "SPECTRUM", "pickerStyle should be sent in upper case")
        cfg["parentID"] = "VIEW1"
        new_picker = ColorPicker.from_cfg_dict(cfg)
        new_cfg = new_picker.get_cfg64(["", "DEVICEID", "DASHID", "1"])[0]
        self.assertEqual(new_cfg["pickerStyle"], "SPECTRUM", "pickerStyle should survive a round trip")


    def test_table_without_column_headings(self):
        table = Table("TBL1", columns=3, control_position=ControlPosition(0.1, 0.2, 0.3, 0.4))
        cfg = table.get_cfg64(["", "DEVICEID", "DASHID", "1"])[0]
        self.assertEqual(cfg["colHeadings"], [], "A Table without column headings should have none")
        cfg["parentID"] = "VIEW1"
        self.assertEqual(Table.from_cfg_dict(cfg).get_cfg64([])[0]["columns"], 3, "columns should survive a round trip")


if __name__ == '__main__':
    unittest.main()
